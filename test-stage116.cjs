const assert=require('node:assert/strict');
const fs=require('node:fs');const vm=require('node:vm');
const src=fs.readFileSync('src/app.js','utf8');
const store=new Map();
const sandbox={console,Date,localStorage:{getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v)},document:{querySelector:()=>null},setTimeout:()=>{},};
vm.createContext(sandbox);
// Evaluate application functions while avoiding browser DOM startup bindings.
const cut=src.indexOf("document.addEventListener('click',event=>");
assert(cut>0);
vm.runInContext(src.slice(0,cut),sandbox);
const evaluate=expression=>vm.runInContext(expression,sandbox);
assert.equal(evaluate('latestCaseResult(data.cases[0])'),'Not Run','legacy metadata must not count as execution');
evaluate("data.runs.unshift({id:'RUN-100',name:'retry',project:'SHOP',results:[{caseId:'TC-024',title:'signup',result:'Fail'}]})");
assert.equal(evaluate('latestCaseResult(data.cases[0])'),'Fail');
evaluate("data.runs.unshift({id:'RUN-101',name:'retry2',project:'SHOP',results:[{caseId:'TC-024',title:'signup',result:'Pass'}]})");
assert.equal(evaluate('latestCaseResult(data.cases[0])'),'Pass');
assert.equal(evaluate("data.runs.find(x=>x.id==='RUN-100').results[0].result"),'Fail','history must stay intact');
assert.match(evaluate('tcCollectionDetail.toString()'),/caseResultPill/);
assert.doesNotMatch(evaluate('workshop.toString()'),/name="status"/,'direct TC result editing removed');
assert.equal(evaluate("bugVisibilityRows('completed').every(b=>b.status==='Closed')"),true);
assert.equal(evaluate("bugVisibilityRows('active').some(b=>b.status==='Resolved')"),true);
assert.equal(evaluate("updateBugStatus(data.bugs.find(b=>b.id==='BUG-103'),'Closed')"),false,'Cannot skip re-test');
evaluate("data.bugs.find(b=>b.id==='BUG-103').verifications=[{result:'Pass',source:'manual-qa',note:'validated',at:new Date().toISOString()}]");
assert.equal(evaluate("updateBugStatus(data.bugs.find(b=>b.id==='BUG-103'),'Closed')"),true);
assert.equal(evaluate("bugVisibilityRows('completed').some(b=>b.id==='BUG-103')"),true);
evaluate("updateBugStatus(data.bugs.find(b=>b.id==='BUG-103'),'Open')");
assert.equal(evaluate("updateBugStatus(data.bugs.find(b=>b.id==='BUG-103'),'Closed')"),false,'Old verification cannot bypass Resolved');
assert.match(evaluate('dashboard.toString()'),/QA 작업 대기열/);
assert.match(evaluate('bugDetail.toString()'),/QA 재검증 기록/);
assert.match(evaluate('settings.toString()'),/localStorage/);
assert.match(fs.readFileSync('index.html','utf8'),/app\.js\?v=1\.1\.6/);
console.log('PASS 13 checks: latest run, historical preservation, TC editor, retest workflow, dashboard, privacy/cache');
