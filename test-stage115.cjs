const fs=require('fs'),vm=require('vm'),assert=require('assert');
const s=fs.readFileSync(__dirname+'/src/app.js','utf8');
const ctx=vm.createContext({localStorage:{getItem:()=>null},console});
vm.runInContext(s.split('const statusClass=')[0],ctx);
assert.strictEqual(vm.runInContext("projectStage('SHOP')",ctx),'active');
assert.strictEqual(vm.runInContext("projectStage('MISSING')",ctx),'unassigned');
vm.runInContext("data.projects.find(p=>p.key==='SHOP').status='Completed'",ctx);
assert.strictEqual(vm.runInContext("projectStage('SHOP')",ctx),'completed');
assert.strictEqual(vm.runInContext("matchesProjectStage('SHOP','active')",ctx),false);
assert.strictEqual(vm.runInContext("matchesProjectStage('SHOP','completed')",ctx),true);
assert.strictEqual(vm.runInContext("matchesProjectStage('MOB','active')",ctx),true);
assert.strictEqual(vm.runInContext("matchesProjectStage('MOB','completed')",ctx),false);
assert(s.includes('data-open-project-suites="${esc(p.key)}"'),'Linked cases CTA');
assert(s.includes("tcHubFocusedProject=key"),'Detail-to-suite navigation');
assert(s.includes("tcHubProject=project.status==='Completed'?'completed':'active'"),'Completed scoped navigation');
assert(s.includes("tcHubFocusedProject=''"),'Scope reset');
assert(s.includes('진행 중인 프로젝트</option><option value="completed"'),'Two category options');
assert(!s.includes('id="bug-project-filter" aria-label="프로젝트 필터"'),'No individual bug project names');
const index=fs.readFileSync(__dirname+'/index.html','utf8');assert(index.includes('app.js?v=1.1.5'));
console.log('PASS v1.1.5: project status grouping, project-to-suite link, filters and cache busting');
